alter table public.chamados drop constraint chamados_verificacao_origem_check;

alter table public.chamados
  add constraint chamados_verificacao_origem_check check (
    user_id is null
    or (nome_informado is null
      and cadastro_informado is null
      and ultimo_acesso_informado is null
      and titulos_informados is null)
  );

alter table public.chamados add column numero bigint;

update public.chamados as c
   set numero = ordem.posicao
  from (select id, row_number() over (order by created_at, id) as posicao from public.chamados) as ordem
 where c.id = ordem.id;

alter table public.chamados alter column numero set not null;

alter table public.chamados alter column numero add generated by default as identity;

select setval(
  pg_get_serial_sequence('public.chamados', 'numero'),
  coalesce((select max(numero) from public.chamados), 0) + 1,
  false
);

alter table public.chamados add constraint chamados_numero_key unique (numero);
